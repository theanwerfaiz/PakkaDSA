// Copies the self-hosted font files from the @fontsource packages into public/fonts/
// and writes src/styles/fonts.css. Run after changing a font version: node scripts/copy-fonts.mjs
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const FONTS = [
  { pkg: 'instrument-sans', subsets: ['latin', 'latin-ext'], weights: [400, 500, 600, 700] },
  { pkg: 'kalam', subsets: ['devanagari', 'latin', 'latin-ext'], weights: [400, 700] },
  { pkg: 'jetbrains-mono', subsets: ['latin', 'latin-ext'], weights: [400, 500] },
  { pkg: 'noto-sans-devanagari', subsets: ['devanagari'], weights: [400, 500, 600] },
];

const OUT = 'public/fonts';
mkdirSync(OUT, { recursive: true });
let css =
  '/* Generated by scripts/copy-fonts.mjs. Fonts are SIL OFL 1.1; see public/fonts/*.LICENSE.txt */\n';

for (const { pkg, subsets, weights } of FONTS) {
  const dir = join('node_modules', '@fontsource', pkg);
  copyFileSync(join(dir, 'LICENSE'), join(OUT, `${pkg}.LICENSE.txt`));
  for (const subset of subsets) {
    for (const weight of weights) {
      const file = `${pkg}-${subset}-${weight}-normal.woff2`;
      copyFileSync(join(dir, 'files', file), join(OUT, file));
      const all = readFileSync(join(dir, `${weight}.css`), 'utf8');
      const start = all.indexOf(`/* ${pkg}-${subset}-${weight}-normal */`);
      if (start < 0) throw new Error(`No @font-face for ${file}`);
      const face = all
        .slice(all.indexOf('@font-face', start), all.indexOf('}', start) + 1)
        .replace(/src: [^;]+;/, `src: url(/fonts/${file}) format('woff2');`);
      css += face.trim() + '\n';
    }
  }
}
writeFileSync('src/styles/fonts.css', css);
console.log('fonts copied');
